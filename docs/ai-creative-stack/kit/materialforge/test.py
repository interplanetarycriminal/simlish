"""Test for materialforge. Run from anywhere: python kit/materialforge/test.py

Generates every preset at 256 px through the CLI, then checks tileability,
normal-map correctness, value ranges, colour-space metadata and determinism.
Writes out/result.json and out/preview_sheet.png. Exits 0 only on pass.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import materialforge as mf  # noqa: E402

OUT = HERE / "out"
WORK = OUT / "_work"
SIZE = 256
SEED = 7
KEEP_FULL_SET = ["wood", "rust"]  # full map sets kept in out/ (size budget); all are regenerated by the test

# expected value bands per preset
METAL_KIND = {"wood": "dielectric", "brushed-metal": "metal", "painted-plastic": "dielectric",
              "fabric": "dielectric", "stone": "dielectric", "rust": "mixed"}
ROUGH_BAND = {"wood": (0.4, 0.8), "brushed-metal": (0.15, 0.5), "painted-plastic": (0.25, 0.55),
              "fabric": (0.75, 1.0), "stone": (0.6, 0.95), "rust": (0.35, 0.9)}

failures: list[str] = []


def check(cond, msg):
    if not cond:
        failures.append(msg)
    return bool(cond)


def load(path):
    im = Image.open(path)
    a = np.array(im)
    return im.mode, a


def seam_stats(a):
    """Compare the wrap seam with interior neighbour differences, both axes.

    For axis x: d_j = mean |a[:, j+1] - a[:, j]| over the column pair,
    seam = mean |a[:, 0] - a[:, -1]|. Pass when the seam is not an outlier:
    seam <= mean(d) + 3 std(d) + 0.5/255.
    """
    a = a.astype(np.float64)
    if a.ndim == 2:
        a = a[..., None]
    res = {}
    for name, ax in (("x", 1), ("y", 0)):
        d = np.abs(np.diff(a, axis=ax)).mean(axis=(2, 1 - ax))
        first = np.take(a, 0, axis=ax)
        last = np.take(a, -1, axis=ax)
        seam = float(np.abs(first - last).mean())
        bound = float(d.mean() + 3 * d.std() + 0.5 / 255.0)
        res[name] = {"seam": round(seam, 5), "interior_mean": round(float(d.mean()), 5),
                     "bound": round(bound, 5), "ok": seam <= bound}
    return res


def preview_cell(img_rgb, tile=96):
    """2x2 tiling of a map downscaled to tile px."""
    t = Image.fromarray(img_rgb).resize((tile, tile), Image.LANCZOS)
    cell = Image.new("RGB", (tile * 2, tile * 2))
    for oy in (0, tile):
        for ox in (0, tile):
            cell.paste(t, (ox, oy))
    return cell


def lit_view(base8, normal8, ao8):
    base = (base8.astype(np.float64) / 255.0) ** 2.2
    n = normal8.astype(np.float64) / 255.0 * 2 - 1
    L = np.array([-0.5, 0.6, 0.62])
    L /= np.linalg.norm(L)
    d = np.clip((n * L).sum(-1), 0, 1)
    ao = ao8.astype(np.float64) / 255.0
    c = base * (0.18 + 0.82 * d)[..., None] * ao[..., None]
    return np.clip(np.round(np.clip(c, 0, 1) ** (1 / 2.2) * 255), 0, 255).astype(np.uint8)


def main():
    t0 = time.time()
    if WORK.exists():
        shutil.rmtree(WORK)
    WORK.mkdir(parents=True)
    report = {"size": SIZE, "seed": SEED, "presets": {}}
    rows = []

    for preset in mf.PRESETS:
        pr = {}
        outdir = WORK / preset
        cmd = [sys.executable, str(HERE / "materialforge.py"), preset, "--size", str(SIZE),
               "--seed", str(SEED), "--out", str(outdir)]
        r = subprocess.run(cmd, capture_output=True, text=True)
        check(r.returncode == 0, f"{preset}: CLI exit {r.returncode}: {r.stderr[-300:]}")
        files = ["base_color.png", "roughness.png", "metallic.png", "normal.png", "height.png", "ao.png",
                 "material.json"]
        missing = [f for f in files if not (outdir / f).exists()]
        if not check(not missing, f"{preset}: missing {missing}"):
            report["presets"][preset] = {"missing": missing}
            continue

        maps = {}
        modes = {}
        for f in files[:-1]:
            modes[f], maps[f] = load(outdir / f)
        check(modes["base_color.png"] == "RGB", f"{preset}: base_color mode {modes['base_color.png']}")
        check(modes["normal.png"] == "RGB", f"{preset}: normal mode {modes['normal.png']}")
        for f in ("roughness.png", "metallic.png", "ao.png"):
            check(modes[f] == "L", f"{preset}: {f} mode {modes[f]}")
        check(maps["height.png"].dtype in (np.uint16, np.int32) and maps["height.png"].max() > 255,
              f"{preset}: height is not 16-bit")
        for f, a in maps.items():
            check(a.shape[:2] == (SIZE, SIZE), f"{preset}: {f} shape {a.shape}")

        # -- tileability
        tiles = {}
        for f, a in maps.items():
            s = seam_stats(a)
            tiles[f] = s
            for axn, v in s.items():
                check(v["ok"], f"{preset}: {f} seam {axn} {v['seam']} > bound {v['bound']}")
        pr["seams"] = {f: {ax: v["seam"] / max(v["interior_mean"], 1e-9) for ax, v in s.items()}
                       for f, s in tiles.items()}

        # -- normals: unit length, +Z hemisphere, gradient sign and scale
        meta = json.loads((outdir / "material.json").read_text(encoding="utf-8"))
        n = maps["normal.png"].astype(np.float64) / 255.0 * 2.0 - 1.0
        length = np.linalg.norm(n, axis=-1)
        len_err = float(np.abs(length - 1.0).max())
        check(len_err < 0.02, f"{preset}: normal length error {len_err:.4f}")
        check(float(n[..., 2].min()) > 0.0, f"{preset}: normal z <= 0")
        h = maps["height.png"].astype(np.float64) / 65535.0
        texel = meta["tile_size_m"] / SIZE
        hd = h * meta["height_depth_m"]
        dhdx = (np.roll(hd, -1, 1) - np.roll(hd, 1, 1)) / (2 * texel)
        dhdrow = (np.roll(hd, -1, 0) - np.roll(hd, 1, 0)) / (2 * texel)
        cx = float(np.corrcoef(n[..., 0].ravel(), -dhdx.ravel())[0, 1])
        cy = float(np.corrcoef(n[..., 1].ravel(), dhdrow.ravel())[0, 1])
        expect = np.stack([-dhdx, dhdrow, np.ones_like(hd)], -1)
        expect /= np.linalg.norm(expect, axis=-1, keepdims=True)
        # Sign test: where the height slope is clearly above 8-bit quantisation, the stored
        # normal must lean the same way (x against dh/dx; y, OpenGL +Y up, with dh/drow).
        agree = {}
        for ax, name in ((0, "x"), (1, "y")):
            mask = np.abs(expect[..., ax]) > 0.012
            cnt = int(mask.sum())
            frac = float((np.sign(n[..., ax][mask]) == np.sign(expect[..., ax][mask])).mean()) if cnt else 1.0
            agree[name] = {"pixels": cnt, "sign_agreement": round(frac, 4)}
            check(frac >= 0.99, f"{preset}: normal {name} sign agrees with height slope on only {frac:.3f}")
        check(agree["x"]["pixels"] + agree["y"]["pixels"] > 0.05 * SIZE * SIZE,
              f"{preset}: normal map is nearly flat")
        scale_err = float(np.abs(expect - n).mean())
        check(scale_err < 0.01, f"{preset}: normal differs from height-derived normal by {scale_err:.4f}")
        tilt = float(np.degrees(np.arctan2(np.hypot(n[..., 0], n[..., 1]), n[..., 2])).mean())
        pr["normal"] = {"max_len_err": round(len_err, 4), "corr_x": round(cx, 4), "corr_y": round(cy, 4),
                        "sign": agree,
                        "mean_abs_err_vs_height": round(scale_err, 5), "mean_tilt_deg": round(tilt, 2)}

        # -- value ranges
        base = maps["base_color.png"].astype(np.float64) / 255.0
        rough = maps["roughness.png"].astype(np.float64) / 255.0
        metal = maps["metallic.png"].astype(np.float64) / 255.0
        ao = maps["ao.png"].astype(np.float64) / 255.0
        lum = base.mean(-1)
        p1, p99 = np.percentile(lum, [1, 99])
        check(p1 > 0.02 and p99 < 0.97, f"{preset}: base colour out of albedo range p1={p1:.3f} p99={p99:.3f}")
        rlo, rhi = ROUGH_BAND[preset]
        check(rlo <= rough.mean() <= rhi, f"{preset}: roughness mean {rough.mean():.3f} not in {ROUGH_BAND[preset]}")
        check(rough.min() >= 0.02 - 1e-9, f"{preset}: roughness min {rough.min():.3f}")
        kind = METAL_KIND[preset]
        if kind == "metal":
            check(metal.min() > 0.98, f"{preset}: metallic min {metal.min():.3f} (expected 1)")
            check(lum.mean() > 0.5, f"{preset}: metal base colour too dark {lum.mean():.3f}")
        elif kind == "dielectric":
            check(metal.max() < 0.02, f"{preset}: metallic max {metal.max():.3f} (expected 0)")
        else:
            binary = float(((metal < 0.1) | (metal > 0.9)).mean())
            frac_metal = float((metal > 0.5).mean())
            check(binary > 0.9, f"{preset}: only {binary:.3f} of metallic is near 0 or 1")
            check(0.2 < frac_metal < 0.8, f"{preset}: metal fraction {frac_metal:.3f}")
            pr["metallic_binary_fraction"] = round(binary, 4)
            pr["metal_fraction"] = round(frac_metal, 4)
        check(0.0 <= ao.min() and ao.mean() > 0.6, f"{preset}: AO mean {ao.mean():.3f}")
        check(h.min() == 0.0 and h.max() == 1.0, f"{preset}: height does not use full range")
        pr["ranges"] = {"base_lum_p1": round(float(p1), 3), "base_lum_p99": round(float(p99), 3),
                        "rough_mean": round(float(rough.mean()), 3), "metal_mean": round(float(metal.mean()), 3),
                        "ao_mean": round(float(ao.mean()), 3)}

        # -- metadata
        cs = {k: v["colorspace"] for k, v in meta["maps"].items()}
        check(cs.get("base_color") == "sRGB", f"{preset}: base colour colour space {cs.get('base_color')}")
        for k in ("roughness", "metallic", "normal", "height", "ao"):
            check(cs.get(k) == "Non-Color", f"{preset}: {k} colour space {cs.get(k)}")
        check("principled_bsdf" in meta and "Roughness" in meta["principled_bsdf"], f"{preset}: no BSDF block")

        # -- determinism: same seed identical (in-process and CLI), different seed differs
        g1 = mf.generate(preset, SIZE, SEED)
        g2 = mf.generate(preset, SIZE, SEED)
        same = all(np.array_equal(g1[k], g2[k]) for k in ("base_color", "roughness", "metallic", "normal",
                                                           "height", "ao"))
        check(same, f"{preset}: generate() not deterministic")
        cli_same = (np.array_equal(g1["base_color"], maps["base_color.png"])
                    and np.array_equal(g1["normal"], maps["normal.png"])
                    and np.array_equal(g1["height"].astype(np.int64), maps["height.png"].astype(np.int64)))
        check(cli_same, f"{preset}: CLI output differs from generate() with same seed")
        g3 = mf.generate(preset, SIZE, SEED + 1)
        check(not np.array_equal(g1["height"], g3["height"]), f"{preset}: different seed gave same height")
        pr["deterministic"] = bool(same and cli_same)

        report["presets"][preset] = pr
        rows.append((preset, maps))

    # -- negative control: the seam test must reject a non-periodic crop and accept a rolled tile
    stone = [m for p, m in rows if p == "stone"]
    base = stone[0]["base_color.png"] if stone else None
    if base is not None:
        crop = seam_stats(base[:200, :200])
        rolled = seam_stats(np.roll(base, (37, 91), (0, 1)))
        check(not crop["x"]["ok"] and not crop["y"]["ok"], "negative control: non-periodic crop passed seam test")
        check(rolled["x"]["ok"] and rolled["y"]["ok"], "control: rolled periodic tile failed seam test")
        report["seam_controls"] = {"crop_200px": crop, "rolled": rolled}

    # -- preview sheet: per preset, 2x2 tiled base colour, lit relief, normal
    tile = 96
    cell = tile * 2
    pad = 4
    sheet = Image.new("RGB", (3 * cell + 4 * pad, len(rows) * cell + (len(rows) + 1) * pad), (24, 24, 24))
    for r, (preset, maps) in enumerate(rows):
        imgs = [maps["base_color.png"], lit_view(maps["base_color.png"], maps["normal.png"], maps["ao.png"]),
                maps["normal.png"]]
        for c, im in enumerate(imgs):
            sheet.paste(preview_cell(im, tile), (pad + c * (cell + pad), pad + r * (cell + pad)))
    sheet.save(OUT / "preview_sheet.png", optimize=True)

    # -- keep a small committed set
    for preset in mf.PRESETS:
        dst = OUT / preset
        if dst.exists():
            shutil.rmtree(dst)
        src = WORK / preset
        if not src.exists():
            continue
        dst.mkdir(parents=True)
        names = [p.name for p in src.iterdir()] if preset in KEEP_FULL_SET else ["material.json"]
        for name in names:
            shutil.copy2(src / name, dst / name)
    shutil.rmtree(WORK, ignore_errors=True)

    report["pass"] = not failures
    report["failures"] = failures
    report["seconds"] = round(time.time() - t0, 1)
    (OUT / "result.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps({"pass": report["pass"], "failures": failures, "seconds": report["seconds"]}, indent=2))
    return 0 if report["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
